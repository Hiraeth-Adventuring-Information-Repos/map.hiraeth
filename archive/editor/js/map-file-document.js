(function expose(root, factory) {
    const api = factory();
    if (typeof module === 'object' && module.exports) module.exports = api;
    if (root) root.MapFileDocument = api;
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
    const collections = ['pointsOfInterest', 'regions', 'lines', 'roads', 'journeys'];
    const clone = value => value === undefined ? undefined : JSON.parse(JSON.stringify(value));
    const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b);
    const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
    const own = (value, key) => Object.prototype.hasOwnProperty.call(value || {}, key);

    // Compare against what the UI initially displayed, never against its lossy
    // normalization of the source. Untouched source values remain authoritative.
    function patch(raw, baseline, edited, identityKey) {
        if (equal(baseline, edited)) return clone(raw);
        if (Array.isArray(baseline) && Array.isArray(edited) && Array.isArray(raw)) {
            if (identityKey && baseline.some(value => object(value) && own(value, identityKey))) {
                const used = new Set();
                return edited.map(value => {
                    const identity = value?.[identityKey];
                    if (!identity) return clone(value);
                    const index = baseline.findIndex(previous => previous?.[identityKey] === identity);
                    if (index < 0 || used.has(identity)) throw new Error('Invalid nested entry identity; reload before saving.');
                    used.add(identity);
                    return patch(raw[index], baseline[index], value, identityKey);
                });
            }
            if (baseline.length === edited.length) return edited.map((value, index) => patch(raw[index], baseline[index], value, identityKey));
            // Insertions/deletions retain untouched source vertices and rich entries.
            const used = new Set();
            return edited.map(value => {
                const index = baseline.findIndex((previous, i) => !used.has(i) && equal(previous, value));
                if (index < 0) return clone(value);
                used.add(index);
                return clone(raw[index]);
            });
        }
        if (!object(baseline) || !object(edited)) return clone(edited);
        const result = object(raw) ? clone(raw) : {};
        for (const key of new Set([...Object.keys(baseline), ...Object.keys(edited)])) {
            if (equal(baseline[key], edited[key]) && own(baseline, key) === own(edited, key)) continue;
            if (!own(edited, key)) delete result[key];
            else Object.defineProperty(result, key, { value: patch(raw?.[key], baseline[key], edited[key], identityKey), enumerable: true, writable: true, configurable: true });
        }
        return result;
    }

    function createSession(rawDocument, normalizedDocument) {
        const raw = clone(rawDocument);
        const editableDocument = clone(normalizedDocument);
        let identityKey = '__hiraethFileIdentity';
        while (JSON.stringify(raw).includes('"' + identityKey + '"') || JSON.stringify(editableDocument).includes('"' + identityKey + '"')) identityKey += '_';
        const records = {};
        for (const collection of collections) {
            if (!Array.isArray(editableDocument[collection])) continue;
            let sourceKey = collection;
            if (!Array.isArray(raw[sourceKey]) && collection === 'lines' && Array.isArray(raw.roads)) sourceKey = 'roads';
            if (!Array.isArray(raw[sourceKey]) && collection === 'roads' && Array.isArray(raw.lines)) sourceKey = 'lines';
            records[collection] = { sourceKey, features: [] };
            editableDocument[collection].forEach((feature, index) => {
                const identity = collection + ':' + index;
                feature[identityKey] = identity;
                if (Array.isArray(feature.detailSections)) feature.detailSections.forEach((section, sectionIndex) => {
                    section[identityKey] = identity + ':section:' + sectionIndex;
                });
                records[collection].features.push({ identity, raw: clone(raw[sourceKey]?.[index]), baseline: clone(feature) });
            });
        }
        return { editableDocument, snapshot: { raw, baseline: clone(editableDocument), identityKey, records } };
    }

    function buildDocument(snapshot, currentDocument, options = {}) {
        const { raw, baseline, identityKey, records } = snapshot;
        const edited = clone(currentDocument);
        const metadataBaseline = clone(baseline);
        const metadataEdited = clone(edited);
        for (const key of collections) { delete metadataBaseline[key]; delete metadataEdited[key]; }
        // Filter choices are generated by the old editor. Keep existing choices,
        // including unused/custom ones, and add newly introduced choices only.
        delete metadataBaseline.filterGroups;
        delete metadataEdited.filterGroups;
        const result = patch(raw, metadataBaseline, metadataEdited);
        for (const [collection, record] of Object.entries(records)) {
            const current = Array.isArray(edited[collection]) ? edited[collection].slice() : [];
            // Existing editor serializers sort by name on every save. That is
            // presentation, not a user content edit. Preserve source order by
            // default; an explicit reorder UI can opt in.
            if (!options.honorFeatureOrder) {
                const order = new Map(record.features.map((feature, index) => [feature.identity, index]));
                current.sort((a, b) => (order.get(a[identityKey]) ?? Infinity) - (order.get(b[identityKey]) ?? Infinity));
            }
            if (equal(baseline[collection], current)) continue;
            const used = new Set();
            result[record.sourceKey] = current.map(feature => {
                const identity = feature[identityKey];
                if (identity && used.has(identity)) throw new Error('Duplicate feature identity; reload before saving.');
                if (identity) used.add(identity);
                const previous = record.features.find(item => item.identity === identity);
                if (identity && !previous) throw new Error('Unknown feature identity; reload before saving.');
                const next = previous ? patch(previous.raw, previous.baseline, feature, identityKey) : clone(feature);
                delete next[identityKey];
                return next;
            });
        }
        for (const collection of collections) {
            if (!records[collection] && Array.isArray(edited[collection]) && edited[collection].length) {
                result[collection] = clone(edited[collection]);
                result[collection].forEach(feature => delete feature[identityKey]);
            }
        }
        if (!equal(baseline.filterGroups, edited.filterGroups)) {
            const merge = (target, incoming) => {
                if (Array.isArray(incoming)) return [...(Array.isArray(target) ? target : []), ...incoming.filter(value => !(Array.isArray(target) ? target : []).some(old => equal(old, value)))];
                if (!object(incoming)) return clone(target === undefined ? incoming : target);
                const next = object(target) ? clone(target) : {};
                for (const key of Object.keys(incoming)) Object.defineProperty(next, key, { value: merge(next[key], incoming[key]), enumerable: true, writable: true, configurable: true });
                return next;
            };
            result.filterGroups = merge(raw.filterGroups, edited.filterGroups);
        }
        const stripIdentity = value => {
            if (!value || typeof value !== 'object') return;
            delete value[identityKey];
            Object.values(value).forEach(stripIdentity);
        };
        stripIdentity(result);
        return result;
    }
    return { createSession, buildDocument };
}));
